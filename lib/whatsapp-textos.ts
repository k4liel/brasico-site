// Polonês: plural com 1 / 2–4 / 5+ (com exceção de 12–14)
const pl3 = (n: number, um: string, poucos: string, muitos: string) => {
  if (n === 1) return um;
  const d = n % 10;
  const c = n % 100;
  return d >= 2 && d <= 4 && (c < 12 || c > 14) ? poucos : muitos;
};

